"""Regenerates src/prompts.txt: SigLIP 2 text embeddings for the action and idle prompts in proto.py.

Needs the SigLIP 2 text model, which the app itself never downloads:
  python tools/prompts.py <models dir>   (with siglip2/text_model_fp16.onnx and siglip2/tokenizer.json in it)
Packages: onnxruntime-directml (or onnxruntime), tokenizers, numpy, pillow.
"""
import os
import sys

import proto

here = os.path.dirname(os.path.abspath(__file__))
models = sys.argv[1]
emb, _, _ = proto.text_embeddings(models)
everything = proto.ACTION + proto.IDLE
with open(os.path.join(here, "..", "src", "prompts.txt"), "w", encoding="utf-8") as f:
    f.write("# SigLIP 2 base-patch16-224 text embeddings (pooler_output, L2-normalised). Generated by tools/prompts.py.\n")
    for kind, prompts in (("action", proto.ACTION), ("idle", proto.IDLE)):
        for p in prompts:
            f.write(kind + "\t" + p + "\n" + " ".join("%.6f" % v for v in emb[everything.index(p)]) + "\n")
print("wrote", len(everything), "prompts")
